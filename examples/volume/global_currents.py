"""
Volume currents around handles and cavities
==========================================

Run ``uv run --locked python examples/volume/global_currents.py`` for headless
checks on a solid ring and a cube with an enclosed cavity. No meshing backend
is required. Append ``--show`` to display the ring's global current, normalized
to 1 A through a cross-sectional cut.

The ring is a voxel approximation with solid-torus topology. Its one added
global current cannot be generated by boundary-zero edge potentials. A cavity
changes the potential gauge but adds no global current. Global modes are
computed from the stacked divergence/transpose-curl nullspace and appended to
independent local curls.
"""

import argparse
from itertools import permutations, product

import numpy as np

from bfieldtools.volume import (
    TetraMesh,
    augmented_flux_basis,
    build_face_current_basis,
    build_topology,
    reconstruct_currents,
    resistance_matrix,
)


def voxel_mesh(omit):
    """Conforming tetrahedral subdivision of a 3-by-3-by-3 voxel cube."""
    vertices = np.array(list(product(range(4), repeat=3)), dtype=float) / 3
    cells = []
    for origin in product(range(3), repeat=3):
        if origin in omit:
            continue
        for axes in permutations(range(3)):
            points = [np.array(origin)]
            for axis in axes:
                point = points[-1].copy()
                point[axis] += 1
                points.append(point)
            cells.append([np.ravel_multi_index(point, (4, 4, 4)) for point in points])
    return TetraMesh(vertices, cells)


def check_space(mesh, expected_global):
    topology = build_topology(mesh)
    space = augmented_flux_basis(topology)
    assert space.n_global == expected_global
    assert space.n_dofs == (
        np.count_nonzero(~topology.boundary_face_mask)
        - len(mesh.tetrahedra)
        + topology.n_components
    )
    np.testing.assert_allclose(
        topology.divergence @ space.fluxes.toarray(), 0, atol=1e-13
    )
    basis = build_face_current_basis(mesh, space)
    print(
        f"{len(mesh.tetrahedra)} cells; {space.n_dofs} independent currents = "
        f"{len(space.local_edges)} local + {space.n_global} global"
    )
    return topology, space, basis


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--show", action="store_true", help="display the global ring current"
    )
    args = parser.parse_args()
    mesh = voxel_mesh(tuple((1, 1, z) for z in range(3)))
    print("Solid ring:")
    topology, space, basis = check_space(mesh, 1)

    triangles = mesh.vertices[topology.faces]
    on_cut = np.all(np.isclose(triangles[:, :, 1], 1 / 3), axis=1)
    on_cut &= np.all(triangles[:, :, 0] >= 2 / 3 - 1e-14, axis=1)
    normals = np.cross(
        triangles[:, 1] - triangles[:, 0], triangles[:, 2] - triangles[:, 0]
    )
    cut = on_cut * np.sign(normals[:, 1])
    cut_flux = cut @ space.fluxes
    np.testing.assert_allclose(cut_flux[:-1], 0, atol=1e-14)
    assert abs(cut_flux[-1]) > 0.1
    coefficients = np.zeros(space.n_dofs)
    coefficients[-1] = 1 / cut_flux[-1]
    fluxes = space.fluxes @ coefficients
    np.testing.assert_allclose(cut @ fluxes, 1)
    currents = reconstruct_currents(basis, coefficients)
    loss = coefficients @ resistance_matrix(basis, 1.0) @ coefficients
    print(
        f"Cross-section current: {cut @ fluxes:.6g} A; Joule loss at rho=1: {loss:.6g} W"
    )

    print("Enclosed cavity:")
    check_space(voxel_mesh(((1, 1, 1),)), 0)
    if args.show:
        import pyvista as pv

        plotter = pv.Plotter()
        plotter.add_mesh(
            mesh.to_pyvista().extract_surface(), opacity=0.15, color="lightgray"
        )
        plotter.add_arrows(
            mesh.cell_centers,
            currents,
            mag=0.1 / np.linalg.norm(currents, axis=1).max(),
        )
        plotter.add_text("Global ring current: 1 A through the cut")
        plotter.add_axes()
        plotter.show()


if __name__ == "__main__":
    main()
